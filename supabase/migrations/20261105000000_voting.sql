CREATE TABLE IF NOT EXISTS public.voting_topics (
    id text PRIMARY KEY,
    title text NOT NULL,
    category text NOT NULL,
    description text NOT NULL,
    skills text[] NOT NULL,
    sort_order smallint NOT NULL CHECK (sort_order > 0)
);

CREATE TABLE IF NOT EXISTS public.voting_totals (
    topic_id text PRIMARY KEY REFERENCES public.voting_topics(id),
    votes bigint NOT NULL DEFAULT 0 CHECK (votes >= 0),
    updated_at timestamptz NOT NULL DEFAULT pg_catalog.clock_timestamp()
);

CREATE TABLE IF NOT EXISTS voting_private.config (
    key text PRIMARY KEY,
    value bytea NOT NULL,
    CHECK (key <> 'matricula_hmac_key' OR pg_catalog.octet_length(value) >= 32)
);

CREATE TABLE IF NOT EXISTS voting_private.votes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id text NOT NULL REFERENCES public.voting_topics(id),
    matricula_hash bytea NOT NULL UNIQUE CHECK (pg_catalog.octet_length(matricula_hash) = 32),
    created_at timestamptz NOT NULL DEFAULT pg_catalog.clock_timestamp()
);

CREATE TABLE IF NOT EXISTS voting_private.administrators (
    user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE
);

