CREATE OR REPLACE FUNCTION public.get_voting_topics()
RETURNS jsonb
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $function$
    SELECT pg_catalog.jsonb_build_object('topics', COALESCE(
        pg_catalog.jsonb_agg(pg_catalog.jsonb_build_object(
            'id', t.id, 'title', t.title, 'category', t.category,
            'description', t.description, 'skills', t.skills
        ) ORDER BY t.sort_order), '[]'::jsonb
    )) FROM public.voting_topics AS t;
$function$;

CREATE OR REPLACE FUNCTION public.is_voting_admin()
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $function$
    SELECT auth.uid() IS NOT NULL AND EXISTS (
        SELECT 1 FROM voting_private.administrators a WHERE a.user_id = auth.uid()
    );
$function$;

CREATE OR REPLACE FUNCTION public.cast_vote(p_topic_id text, p_matricula jsonb)
RETURNS jsonb
LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = ''
AS $function$
DECLARE
    v_matricula text;
    v_key bytea;
    v_vote_id bigint;
BEGIN
    IF pg_catalog.jsonb_typeof(p_matricula) IS DISTINCT FROM 'string' THEN
        RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'INVALID_MATRICULA';
    END IF;
    -- Trim external whitespace only; never complete, truncate or parse a number.
    v_matricula := pg_catalog.regexp_replace(p_matricula #>> '{}', '^[[:space:]]+|[[:space:]]+$', '', 'g');
    IF v_matricula COLLATE "C" !~ '^[0-9]{5}$' THEN
        RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'INVALID_MATRICULA';
    END IF;
    IF p_topic_id IS NULL OR NOT EXISTS (
        SELECT 1 FROM public.voting_topics t WHERE t.id = p_topic_id
    ) THEN
        RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'INVALID_TOPIC';
    END IF;
    SELECT c.value INTO STRICT v_key FROM voting_private.config c WHERE c.key = 'matricula_hmac_key';
    INSERT INTO voting_private.votes (topic_id, matricula_hash)
    VALUES (p_topic_id, extensions.hmac(pg_catalog.convert_to(v_matricula, 'UTF8'), v_key, 'sha256'))
    ON CONFLICT (matricula_hash) DO NOTHING
    RETURNING id INTO v_vote_id;
    IF v_vote_id IS NULL THEN
        RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'VOTE_ALREADY_RECORDED';
    END IF;
    INSERT INTO public.voting_totals (topic_id, votes, updated_at)
    VALUES (p_topic_id, 1, pg_catalog.clock_timestamp())
    ON CONFLICT (topic_id) DO UPDATE
    SET votes = public.voting_totals.votes + 1, updated_at = EXCLUDED.updated_at;
    RETURN pg_catalog.jsonb_build_object('topicId', p_topic_id);
END;
$function$;

CREATE OR REPLACE FUNCTION public.get_voting_metrics()
RETURNS jsonb
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = ''
AS $function$
DECLARE
    v_total bigint;
    v_result jsonb;
BEGIN
    IF NOT public.is_voting_admin() THEN
        RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'ADMIN_REQUIRED';
    END IF;
    SELECT pg_catalog.count(*) INTO v_total FROM voting_private.votes;
    WITH topic_counts AS (
        SELECT t.*, totals.votes FROM public.voting_topics t
        JOIN public.voting_totals totals ON totals.topic_id = t.id
    ), category_counts AS (
        SELECT category, pg_catalog.sum(votes) AS votes, pg_catalog.min(sort_order) AS sort_order
        FROM topic_counts GROUP BY category
    ), daily_counts AS (
        SELECT (created_at AT TIME ZONE 'America/Sao_Paulo')::date AS date, pg_catalog.count(*) AS votes
        FROM voting_private.votes GROUP BY 1
    )
    SELECT pg_catalog.jsonb_build_object(
        'totalVotes', v_total,
        'topics', (SELECT pg_catalog.jsonb_agg(pg_catalog.jsonb_build_object(
            'id', t.id, 'title', t.title, 'category', t.category,
            'description', t.description, 'skills', t.skills, 'votes', t.votes,
            'percentage', CASE WHEN v_total = 0 THEN 0 ELSE pg_catalog.round(100.0 * t.votes / v_total, 2) END
        ) ORDER BY t.votes DESC, t.sort_order) FROM topic_counts t),
        'categories', (SELECT pg_catalog.jsonb_agg(pg_catalog.jsonb_build_object(
            'name', c.category, 'votes', c.votes,
            'percentage', CASE WHEN v_total = 0 THEN 0 ELSE pg_catalog.round(100.0 * c.votes / v_total, 2) END
        ) ORDER BY c.sort_order) FROM category_counts c),
        'timeline', COALESCE((SELECT pg_catalog.jsonb_agg(pg_catalog.jsonb_build_object(
            'date', d.date, 'votes', d.votes
        ) ORDER BY d.date) FROM daily_counts d), '[]'::jsonb),
        'leaders', CASE WHEN v_total = 0 THEN '[]'::jsonb ELSE (
            SELECT pg_catalog.jsonb_agg(t.id ORDER BY t.sort_order)
            FROM topic_counts t WHERE t.votes = (SELECT pg_catalog.max(votes) FROM topic_counts)
        ) END,
        'updatedAt', pg_catalog.to_char(pg_catalog.clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
    ) INTO v_result;
    RETURN v_result;
END;
$function$;

